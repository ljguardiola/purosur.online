import { describe, expect, it } from "vitest";
import { isPublicAddress } from "./public-address.js";

describe("isPublicAddress", () => {
  it.each([
    "8.8.8.8",
    "1.1.1.1",
    "93.184.216.34",
    "172.15.255.255",
    "172.32.0.0",
    "100.63.255.255",
    "100.128.0.0",
    "198.17.255.255",
    "198.20.0.0",
    "169.253.255.255",
    "223.255.255.255",
    "2606:4700:4700::1111",
    "2001:4860:4860::8888",
    "2001:db9::1",
    "::ffff:8.8.8.8",
    "::ffff:808:808",
    "64:ff9b::8.8.8.8",
    "::8.8.8.8",
  ])("accepts the public address %s", (address) => {
    expect(isPublicAddress(address)).toBe(true);
  });

  it.each([
    "0.0.0.0",
    "0.1.2.3",
    "127.0.0.1",
    "127.255.255.254",
    "10.0.0.1",
    "10.255.255.255",
    "172.16.0.1",
    "172.31.255.255",
    "192.168.1.1",
    "100.64.0.1",
    "100.127.255.255",
    "169.254.0.1",
    "169.254.169.254",
    "224.0.0.1",
    "239.255.255.255",
    "240.0.0.1",
    "255.255.255.255",
    "198.18.0.1",
    "198.19.255.255",
    "192.0.2.1",
    "198.51.100.1",
    "203.0.113.1",
    "192.0.0.1",
    "::",
    "::1",
    "fc00::1",
    "fd00:ec2::254",
    "fdff::1",
    "fe80::1",
    "febf::1",
    "ff02::1",
    "2001:db8::1",
    "100::1",
    "::ffff:127.0.0.1",
    "::ffff:7f00:1",
    "::ffff:10.0.0.1",
    "::ffff:169.254.169.254",
    "::127.0.0.1",
    "::7f00:1",
    "64:ff9b::127.0.0.1",
    "64:ff9b::a9fe:a9fe",
  ])("refuses the non public address %s", (address) => {
    expect(isPublicAddress(address)).toBe(false);
  });

  it.each(["", "not an address", "1.2.3", "1.2.3.4.5", "256.1.1.1", "::g"])(
    "refuses the text %j that is no address",
    (text) => {
      expect(isPublicAddress(text)).toBe(false);
    },
  );
});
